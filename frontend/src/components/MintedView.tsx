import { useState } from "react";
import { Link } from "react-router-dom";
import { useReadContract } from "wagmi";
import { mainnet, base, sepolia } from "wagmi/chains";
import type { Address } from "viem";
import { muriAbi } from "../abis/muri-abi";
import FilePreview from "./FilePreview";
import GatewayLink from "./GatewayLink";
import { Button, ButtonLink, Loader, StatusLabel } from "./ui";
import type { Tone } from "./ui";
import { useLinkProbes } from "../hooks/useLinkHealth";
import type { LinkHealth } from "../hooks/useLinkHealth";
import { formatBytes, MURI_ADDRESS, shortAddress } from "../lib/muri";
import type { Attribute } from "../lib/muri";

const NETWORKS: Record<number, { name: string; explorer: string; manifold: string; opensea?: string }> = {
	[mainnet.id]: { name: "Ethereum", explorer: "https://etherscan.io", manifold: "ethereum", opensea: "ethereum" },
	[base.id]: { name: "Base", explorer: "https://basescan.org", manifold: "base", opensea: "base" },
	// OpenSea closed its testnets, so Sepolia tokens have no OpenSea page.
	[sepolia.id]: { name: "Sepolia", explorer: "https://sepolia.etherscan.io", manifold: "sepolia" },
};

const health: Record<LinkHealth, { tone: Tone; label: string }> = {
	checking: { tone: "neutral", label: "Checking" },
	live: { tone: "up", label: "Live" },
	dead: { tone: "signal", label: "Dead" },
	unreachable: { tone: "signal", label: "Unreachable" },
	unverified: { tone: "neutral", label: "Responds" },
};

function Row({ label, children }: { label: string; children: React.ReactNode }) {
	return (
		<div className="flex items-baseline justify-between gap-6 py-2.5 border-b border-line last:border-0">
			<dt className="text-[13px] text-muted shrink-0">{label}</dt>
			<dd className="text-[13px] text-right min-w-0 truncate">{children}</dd>
		</div>
	);
}

function ExternalLink({ href, children }: { href: string; children: React.ReactNode }) {
	return (
		<a
			href={href}
			target="_blank"
			rel="noopener noreferrer"
			className="flex items-center justify-between py-3 border-b border-line micro text-muted hover:text-foreground transition-colors"
		>
			{children}
			<span aria-hidden>↗</span>
		</a>
	);
}

/** The token as MURI stored it: the file, its copies, and the live on-chain page that resolves them. */
export default function MintedView({
	file,
	fileHash,
	mimeType,
	name,
	description,
	attributes,
	uris,
	creator,
	type,
	chainId,
	tokenId,
	txHash,
	displayMode,
	permissions,
	recipient,
	editions,
}: {
	file: File;
	fileHash: string;
	mimeType: string;
	name: string;
	description: string;
	attributes: Attribute[];
	uris: string[];
	creator: Address;
	type: "ERC721" | "ERC1155";
	chainId: number;
	tokenId: string | null;
	txHash?: string;
	displayMode: number;
	permissions: string;
	recipient?: string;
	editions?: number;
}) {
	const [view, setView] = useState<"artwork" | "live">("artwork");
	const network = NETWORKS[chainId];
	const probes = useLinkProbes(uris);
	const liveCount = probes.filter((p) => p.health === "live").length;
	const checking = probes.some((p) => p.health === "checking");

	// The token's own Smart HTML page, generated by the contract: what marketplaces render.
	const html = useReadContract({
		abi: muriAbi,
		address: MURI_ADDRESS,
		functionName: "renderRawHTML",
		args: tokenId ? [creator, BigInt(tokenId)] : undefined,
		chainId: chainId as typeof mainnet.id,
		query: { enabled: view === "live" && Boolean(tokenId) },
	});

	const traits = attributes.filter((a) => a.trait_type.trim() && a.value.trim());
	const title = name.trim() || "Untitled";

	return (
		<div className="grid gap-10 lg:grid-cols-[minmax(0,24rem)_minmax(0,1fr)] lg:gap-12 items-start animate-fade-in">
			<aside className="flex flex-col gap-7 lg:sticky lg:top-20 order-2 lg:order-1">
				<div className="flex flex-col gap-4">
					<Link to="/collections?role=creator" className="text-[13px] text-muted hover:text-foreground transition-colors">
						← {type} · {shortAddress(creator)}
					</Link>
					<h1 className="font-medium leading-[1.02] tracking-tight text-balance text-[clamp(2rem,1.2rem+2.4vw,3rem)]">
						{title}
					</h1>
					{description.trim() && (
						<p className="text-muted leading-relaxed text-pretty whitespace-pre-line">{description.trim()}</p>
					)}
				</div>

				<div className="bg-surface border border-line">
					<div className="flex items-center justify-between gap-4 px-5 py-4 border-b border-line">
						<span className="flex flex-col gap-1">
							<span className="micro text-up inline-flex items-center gap-2">
								<span className="w-1.5 h-1.5 bg-up" aria-hidden />
								Minted
							</span>
							<span className="font-mono text-[clamp(1.4rem,1.2rem+0.6vw,1.75rem)] tabular-nums">
								{tokenId ? `#${tokenId}` : "…"}
							</span>
						</span>
						{network && <span className="micro border border-line-strong px-2.5 py-1.5 text-muted">{network.name}</span>}
					</div>
					<dl className="px-5 py-1.5">
						<Row label="Contract">
							{network ? (
								<a href={`${network.explorer}/address/${creator}`} target="_blank" rel="noopener noreferrer" className="link font-mono">
									{shortAddress(creator)}
								</a>
							) : (
								<span className="font-mono">{shortAddress(creator)}</span>
							)}
						</Row>
						<Row label="Standard">{type === "ERC721" ? "ERC-721" : "ERC-1155"}</Row>
						{type === "ERC1155" && editions !== undefined && <Row label="Editions">{editions}</Row>}
						{recipient && (
							<Row label="Owner">
								<span className="font-mono">{shortAddress(recipient)}</span>
							</Row>
						)}
						<Row label="Display">{displayMode === 1 ? "Smart HTML" : "Direct file"}</Row>
						<Row label="Permissions">{permissions}</Row>
						<Row label="File">
							{mimeType || "Unknown"} · {formatBytes(file.size)}
						</Row>
						<Row label="SHA-256">
							<span className="font-mono" title={fileHash}>
								{fileHash.slice(0, 10)}…{fileHash.slice(-6)}
							</span>
						</Row>
					</dl>
				</div>

				<div className="flex flex-col gap-3">
					<div className="flex items-baseline justify-between gap-4">
						<span className="micro text-muted">
							Stored in {uris.length} place{uris.length === 1 ? "" : "s"}
						</span>
						<span className="micro text-faint">{checking ? "Checking" : `${liveCount} live`}</span>
					</div>
					<ol className="flex flex-col border-t border-line">
						{uris.map((uri, i) => {
							const status = health[probes[i].health];
							return (
								<li key={`${i}-${uri}`} className="flex flex-col gap-1.5 py-3 border-b border-line">
									<GatewayLink uri={uri} className="font-mono text-[12px] leading-relaxed break-all hover:opacity-60 transition-opacity" />
									<StatusLabel tone={status.tone}>{status.label}</StatusLabel>
								</li>
							);
						})}
					</ol>
					{uris.length === 1 && (
						<p className="text-[12px] text-muted">
							One copy means one point of failure. You can add more anytime from Manage this token.
						</p>
					)}
				</div>

				{traits.length > 0 && (
					<div className="flex flex-col gap-3">
						<span className="micro text-muted">Properties</span>
						<dl className="grid grid-cols-2 gap-2">
							{traits.map((a) => (
								<div key={`${a.trait_type}-${a.value}`} className="border border-line px-3 py-2">
									<dt className="micro text-faint truncate">{a.trait_type}</dt>
									<dd className="text-[13px] truncate">{a.value}</dd>
								</div>
							))}
						</dl>
					</div>
				)}

				<div className="flex flex-col">
					{network?.opensea && tokenId && (
						<ExternalLink href={`https://opensea.io/item/${network.opensea}/${creator}/${tokenId}`}>View on OpenSea</ExternalLink>
					)}
					{network && tokenId && (
						<ExternalLink href={`${network.explorer}/nft/${creator}/${tokenId}`}>
							View on {network.explorer.includes("basescan") ? "Basescan" : "Etherscan"}
						</ExternalLink>
					)}
					{network && tokenId && (
						<ExternalLink href={`https://gallery.manifold.xyz/${network.manifold}/${creator}/${tokenId}`}>View on Manifold</ExternalLink>
					)}
					{network && txHash && <ExternalLink href={`${network.explorer}/tx/${txHash}`}>Mint transaction</ExternalLink>}
				</div>

				<div className="flex flex-wrap gap-3">
					{tokenId && (
						<ButtonLink to={`/update?creator=${creator}&type=${type}&token=${tokenId}&chain=${chainId}`}>Manage this token</ButtonLink>
					)}
					<Button variant="secondary" onClick={() => window.location.reload()}>
						Mint another
					</Button>
				</div>
			</aside>

			<section className="flex flex-col gap-3 order-1 lg:order-2 min-w-0" aria-label="Artwork">
				<div className="flex items-center justify-between gap-4">
					<div className="flex gap-1" role="tablist" aria-label="View">
						{(
							[
								["artwork", "Artwork"],
								["live", "Live token"],
							] as const
						).map(([key, label]) => (
							<button
								key={key}
								type="button"
								role="tab"
								aria-selected={view === key}
								onClick={() => setView(key)}
								className={`h-8 px-3 font-mono text-[10px] uppercase tracking-[0.16em] border transition-colors ${
									view === key ? "border-foreground text-foreground" : "border-transparent text-muted hover:text-foreground"
								}`}
							>
								{label}
							</button>
						))}
					</div>
					<span className="text-[12px] text-faint text-right">
						{view === "artwork" ? "Your file, as uploaded" : "The token's on-chain page, resolving its copies right now"}
					</span>
				</div>

				{view === "artwork" ? (
					// The media at its own proportions, as large as fits on screen, like a marketplace page.
					<FilePreview
						file={file}
						bare
						maxHeight="max-h-[70svh] lg:max-h-[calc(100svh-10rem)] w-full"
						className="w-full bg-surface"
					/>
				) : (
				<div className="bg-black h-[60svh] lg:h-[calc(100svh-10rem)] grid place-items-center overflow-hidden">
					{html.isLoading ? (
						<p className="flex items-center gap-3 text-white/60">
							<Loader />
							<span className="micro">Reading the token page from the contract</span>
						</p>
					) : html.data ? (
						<iframe
							srcDoc={html.data}
							title={`${title}, live token page`}
							// Scripts only: the page fetches and hashes the copies, but can't reach this site.
							sandbox="allow-scripts"
							className="w-full h-full border-0"
						/>
					) : (
						<p className="micro text-white/60 px-6 text-center">
							{html.error ? "Couldn't read the token page from the contract." : "The token page appears once the token ID is known."}
						</p>
					)}
				</div>
				)}
			</section>
		</div>
	);
}
